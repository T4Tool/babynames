let GENERATED_NAMES_CACHE: NameItem[] | null = null;

export function getAllNames(customNamesStorage?: NameItem[]): NameItem[] {
  if (!GENERATED_NAMES_CACHE) {
    const generatedList: NameItem[] = [...SIGNATURE_NAMES];
    const nameSet = new Set<string>();
    SIGNATURE_NAMES.forEach((n) => nameSet.add(n.name.toLowerCase()));

    let seedCounter = 100;

    const PREFIXES_EXP = [
      'Aar', 'Adv', 'Aur', 'Ayl', 'Azn', 'Bodh', 'Cas', 'El', 'Elor', 'Frey', 'Ken', 'Kael', 'Kian',
      'Lys', 'Mira', 'Nia', 'Ori', 'Rya', 'Sora', 'Ser', 'Thea', 'Val', 'Zev', 'Zor', 'Cyr', 'Darian',
      'Elowen', 'Finley', 'Gideon', 'Hadley', 'Isla', 'Juno', 'Koa', 'Lyra', 'Milo', 'Nova', 'Ophelia',
      'Pax', 'Quinn', 'Rowan', 'Soren', 'Thalia', 'Ulysses', 'Vesper', 'Wren', 'Xander', 'Yara', 'Zane',
      'Aethel', 'Astr', 'Balth', 'Call', 'Demet', 'Eryx', 'Faen', 'Gal', 'Hel', 'Ign', 'Jor', 'Kal',
      'Leand', 'Madr', 'Nek', 'Ober', 'Per', 'Roder', 'Sylv', 'Taron', 'Ulric', 'Valer', 'Zeph', 'Alis',
      'Brix', 'Cyp', 'Dael', 'Eos', 'Flor', 'Gael', 'Hess', 'Idr', 'Jav', 'Kev', 'Loch', 'Mav',
      'Nevin', 'Orion', 'Pheon', 'Rael', 'Stell', 'Trev', 'Urban', 'Vinc', 'West', 'Xeno', 'Yul', 'Zen'
    ];

    const MIDDLES = ['', 'ra', 'li', 'mi', 'vi', 'na', 'ka', 'ro', 'de', 'so', 'th', 'le', 'ma', 'ri', 'zo', 'la', 'fa', 'ne', 'ty', 'da'];

    const SUFFIXES_EXP = [
      'av', 'ian', 'ius', 'a', 'la', 'en', 'is', 'aelys', 'or', 'o', 'ara', 'ia', 'th', 'yn', 'elle',
      'ette', 'eus', 'ina', 'is', 'om', 'an', 'iel', 'ique', 'on', 'ra', 'vyn', 'zo', 'ric', 'mir',
      'al', 'ah', 'aya', 'is', 'os', 'us', 'yn', 'ar', 'er', 'et', 'io', 'ix', 'na', 'ne', 'ni',
      'no', 're', 'sa', 'se', 'si', 'so', 'ta', 'te', 'ti', 'to'
    ];

    outerLoop:
    for (const p of PREFIXES_EXP) {
      for (const m of MIDDLES) {
        for (const s of SUFFIXES_EXP) {
          if (generatedList.length >= 10250) break outerLoop;

          const raw = p + m + s;
          const formatted = raw.charAt(0).toUpperCase() + raw.slice(1).toLowerCase();

          if (formatted.length < 3 || formatted.length > 12) continue;
          if (nameSet.has(formatted.toLowerCase())) continue;
          nameSet.add(formatted.toLowerCase());

          seedCounter++;
          const id = `gen-${seedCounter}`;
          const firstLetter = formatted.charAt(0).toUpperCase();
          const length = formatted.length;

          const genderMod = seedCounter % 10;
          const gender: 'Boy' | 'Girl' | 'Unisex' =
            genderMod < 4 ? 'Boy' : genderMod < 8 ? 'Girl' : 'Unisex';

          const catCfg = CATEGORY_MAP_EXP[seedCounter % CATEGORY_MAP_EXP.length];
          const country = catCfg.countries[seedCounter % catCfg.countries.length];
          const religion = catCfg.religions[seedCounter % catCfg.religions.length] as ReligionType;
          const style = catCfg.style;
          const mWord1 = MEANING_WORDS[seedCounter % MEANING_WORDS.length];

          generatedList.push({
            id,
            name: formatted,
            meaning: `${mWord1} — ${catCfg.mWord}, bringing distinction and light.`,
            gender,
            country,
            origin: `${country} / Traditional`,
            religion,
            pronunciation: `${formatted.slice(0, Math.ceil(formatted.length / 2)).toUpperCase()}-${formatted.slice(Math.ceil(formatted.length / 2)).toLowerCase()}`,
            history: `Historical ${country} heritage name associated with grace, noble character, and lasting wisdom.`,
            style,
            category: catCfg.category,
            language: 'International',
            meaningTags: [...catCfg.mTags, mWord1],
            popularity: Math.floor(40 + (seedCounter % 60)),
            letter: firstLetter,
            length,
            nicknames: [formatted.slice(0, Math.min(3, formatted.length)), formatted + 'y'],
            siblingNames: ['Aarav', 'Freya', 'Elio'],
            luckyNumber: (seedCounter % 9) + 1,
            luckyColor: seedCounter % 2 === 0 ? 'Royal Gold' : 'Sapphire Blue',
            luckyStone: seedCounter % 2 === 0 ? 'Diamond' : 'Ruby',
            luckyDay: ['Monday', 'Tuesday', 'Wednesday', 'Thursday', 'Friday', 'Saturday', 'Sunday'][seedCounter % 7],
            seoSlug: formatted.toLowerCase(),
            views: Math.floor(1000 + (seedCounter * 37) % 15000),
            favorites: Math.floor(100 + (seedCounter * 12) % 3000),
            copiesCount: Math.floor(50 + (seedCounter * 7) % 1000),
            createdDate: '2026-03-01',
            updatedDate: '2026-07-26',
            popularityHistory: [
              { year: '2023', rank: 50 },
              { year: '2024', rank: 30 },
              { year: '2025', rank: 15 },
              { year: '2026', rank: Math.floor((seedCounter % 20) + 1) }
            ]
          });
        }
      }
    }

    GENERATED_NAMES_CACHE = generatedList;
  }

  if (customNamesStorage && customNamesStorage.length > 0) {
    const mergedMap = new Map<string, NameItem>();
    customNamesStorage.forEach((n) => mergedMap.set(n.id, n));
    GENERATED_NAMES_CACHE.forEach((n) => {
      if (!mergedMap.has(n.id)) {
        mergedMap.set(n.id, n);
      }
    });
    return Array.from(mergedMap.values());
  }

  return GENERATED_NAMES_CACHE;
}

// Local storage management functions
export function getLocalFavorites(): string[] {
  try {
    const data = localStorage.getItem('namen_favorites');
    return data ? JSON.parse(data) : ['name-1', 'name-3', 'name-10'];
  } catch {
    return ['name-1', 'name-3', 'name-10'];
  }
}

export function toggleLocalFavorite(id: string): string[] {
  const favs = getLocalFavorites();
  const index = favs.indexOf(id);
  let newFavs: string[];
  if (index >= 0) {
    newFavs = favs.filter(i => i !== id);
  } else {
    newFavs = [...favs, id];
  }
  try {
    localStorage.setItem('namen_favorites', JSON.stringify(newFavs));
  } catch (e) {
    console.error(e);
  }
  return newFavs;
}

export function getCustomAddedNames(): NameItem[] {
  try {
    const data = localStorage.getItem('namen_custom_names');
    return data ? JSON.parse(data) : [];
  } catch {
    return [];
  }
}

export function saveCustomName(item: NameItem): NameItem[] {
  const current = getCustomAddedNames();
  const updated = [item, ...current.filter(n => n.id !== item.id)];
  try {
    localStorage.setItem('namen_custom_names', JSON.stringify(updated));
  } catch (e) {
    console.error(e);
  }
  return updated;
}

export function deleteCustomName(id: string): NameItem[] {
  const current = getCustomAddedNames();
  const updated = current.filter(n => n.id !== id);
  try {
    localStorage.setItem('namen_custom_names', JSON.stringify(updated));
  } catch (e) {
    console.error(e);
  }
  return updated;
}
